// დაწერეთ პროგრამა, რომელიც დაითვლის რამდენი ლუწი და რამდენი კენტი რიცხვია მასივში.
// ამოცანა შეასრულეთ forEach მეთოდის გამოყენებით.

const nums = [120 , 10 , 2 , 3 , 3 , 7 , 9]
let odd = 0
let even = 0



nums.forEach(num => {
    if (num % 2 === 0){
        even ++
    }
    else{
        odd ++
    }
})

console.log("Even : " + even , "Odd : " +  odd)